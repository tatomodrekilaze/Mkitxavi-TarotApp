export function greetingWords(lang: Lang): string[] {
  const base = [
    "hello",
    "hi",
    "hey",
    "yo",
    "hallo",
    "thanks",
    "thank you",
    "bye",
    "ok",
    "okay",
    "gamarjoba",
  ];
  const extra: Record<Lang, string[]> = {
    en: ["good morning", "good night", "sup"],
    ka: ["გამარჯობა", "გამარჯობათ", "ჰეი", "სალამი", "მადლობა", "კარგი", "ნიჩეო"],
  };
  return [...base, ...extra[lang]];
}

/** Coerce legacy Russian preference to Georgian. */
export function normalizeLang(raw: string | null | undefined): Lang | null {
  if (raw === "ka" || raw === "en") return raw;
  if (raw === "ru") return "ka";
  return null;
}
